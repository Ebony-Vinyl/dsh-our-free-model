/**
 * Desktop client health: the cookie-bloat detector and its repair script.
 *
 * The desktop shell mints one browser-session auth cookie per launch whose
 * name embeds the (random) loopback port, while browsers match cookies by
 * host alone — so every relaunch leaves one dead `dsh-auth-*` cookie behind
 * until the Cookie header crosses node's 16 KiB parse limit and the server
 * starts replying 431 to everything, which the shell surfaces as
 * "desktop welcome: Web authentication failed".
 *
 * What this module reports is deliberately narrow: a file size and a
 * modification time, plus whether the repair script exists. No cookie
 * content, no host key, no value ever leaves the disk — the panel needs
 * "is it bloated?" and "is the repair ready?", nothing else.
 *
 * The repair never touches the database while the shell runs (Chromium
 * holds it). It writes a standalone PowerShell script under
 * `DSH_HOME/our-free-model/` that waits for the shell to exit, backs the
 * database up into %TEMP%, and deletes it — rerunning the script is
 * idempotent, and the plugin itself is never the one deleting user state.
 *
 * @module src/client-health.js
 */

import fs from 'node:fs'
import path from 'node:path'
import os from 'node:os'
import { resolveDshHome, DATA_DIR_NAME } from './store.js'

/** Chromium keeps this many cookies of this shape before the header tips over;
 *  observed at ~70 on real installs (each entry ≈ 200+ bytes of header). */
export const COOKIE_BLOAT_WARN_COUNT = 40

/** The desktop shell's Electron user-data Network directory, as this plugin
 *  resolves it. `electron-user-data` is the path dsh-desktop-next pins via
 *  app.setPath; if a future shell renames it the probe answers `unverified`
 *  instead of guessing. */
export function cookieDbPath() {
  return path.join(resolveDshHome(), 'electron-user-data', 'Network', 'Cookies')
}

/** Where the generated repair script lands. */
export function repairScriptPath() {
  return path.join(resolveDshHome(), DATA_DIR_NAME, 'fix-cookie-bloat.ps1')
}

/**
 * Read the cookie database's size and mtime — never its contents.
 *
 * A locked database (shell running) is still statable on Windows, so the
 * reading works live. A missing database means the shell has not run here,
 * or the layout changed: `unverified`, not a guess.
 *
 * @returns {{state: 'ok'|'unverified', bytes?: number, modifiedAt?: number}}
 */
export function cookieDbStat() {
  const file = cookieDbPath()
  try {
    const stat = fs.statSync(file)
    if (!stat.isFile()) return { state: 'unverified' }
    return { state: 'ok', bytes: stat.size, modifiedAt: Math.round(stat.mtimeMs) }
  } catch {
    return { state: 'unverified' }
  }
}

/**
 * The full health view the API route returns.
 *
 * `suspect` is a size heuristic over the SQLite file, honest about being a
 * heuristic: 20 KB is one fresh database (two cookies), and growth beyond
 * ~3 MB tracks the pile-up this module exists to catch. `repairReady`
 * answers whether the generated script is on disk and newer than the
 * plugin's copy of the template — a stale script is not `ready`.
 *
 * @returns {object}
 */
export function clientHealth() {
  const db = cookieDbStat()
  const script = repairScriptStat()
  return {
    cookieDb: {
      ...db,
      // A fresh install's Cookies db is ~20 KB; each dead cookie adds a few
      // hundred bytes. The threshold is deliberately low so the panel flags
      // "worth cleaning" long before 431 actually bites.
      suspect: db.state === 'ok' && db.bytes >= 64 * 1024,
    },
    repairScript: script,
    platform: process.platform,
  }
}

/** Stat the repair script; `stale` when it exists but the template moved on. */
function repairScriptStat() {
  const file = repairScriptPath()
  try {
    const stat = fs.statSync(file)
    return { exists: stat.isFile(), path: file, bytes: stat.size, mtime: Math.round(stat.mtimeMs) }
  } catch {
    return { exists: false, path: file }
  }
}

const REPAIR_SCRIPT = `# fix-cookie-bloat.ps1 - DSH desktop cookie bloat self-heal (generated by dsh-our-free-model)
# Root cause: the desktop shell's auth cookie name embeds the launch port, and
# cookies ignore ports, so relaunches pile same-origin cookies until the Cookie
# header crosses node's 16384-byte limit - the server then answers 431 and the
# welcome screen reports "Web authentication failed".
# Fix: fully quit DSH, back up and delete the Cookies database, relaunch.

param([switch]$Wait)

$ErrorActionPreference = 'Stop'
$network = Join-Path $env:USERPROFILE '.dsh\\electron-user-data\\Network'
$targets = @('Cookies', 'Cookies-journal') | ForEach-Object { Join-Path $network $_ }

function Test-DshRunning {
    return [bool](Get-Process -Name 'DSH NEXT' -ErrorAction SilentlyContinue)
}

if (Test-DshRunning) {
    if (-not $Wait) {
        Write-Host '[!] DSH NEXT is running; the Cookies database is locked.'
        Write-Host '    Quit DSH NEXT from the system tray, then rerun (or use -Wait).'
        exit 2
    }
    Write-Host '[*] Waiting for DSH NEXT to exit...'
    while (Test-DshRunning) { Start-Sleep -Seconds 2 }
    Start-Sleep -Seconds 3
}

$existing = @($targets | Where-Object { Test-Path $_ })
if ($existing.Count -eq 0) {
    Write-Host '[ok] No Cookies database found (already cleaned). Nothing to do.'
    exit 0
}

$stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
$backupDir = Join-Path $env:TEMP "dsh-cookie-backup-$stamp"
New-Item -ItemType Directory -Path $backupDir -Force | Out-Null

foreach ($f in $existing) {
    $name = Split-Path -Leaf $f
    Copy-Item $f (Join-Path $backupDir $name) -Force
    Remove-Item $f -Force
    $size = (Get-Item (Join-Path $backupDir $name)).Length
    Write-Host "[ok] Backed up and removed $name ($size bytes)"
}

Write-Host ''
Write-Host '================================================================='
Write-Host ' Done. Launch DSH NEXT now; welcome auth should be healthy again.'
Write-Host " Backup kept at: $backupDir (delete it once verified)"
Write-Host '================================================================='
exit 0
`

/**
 * Write the repair script through the same atomic-write discipline the
 * credential store uses (temp file + rename), so a crash mid-write cannot
 * leave a truncated .ps1 that a user would then run.
 *
 * @returns {{written: true, path: string}}
 */
export function writeRepairScript() {
  const file = repairScriptPath()
  const dir = path.dirname(file)
  fs.mkdirSync(dir, { recursive: true, mode: 0o700 })
  const temp = path.join(dir, `.${path.basename(file)}.${process.pid}.tmp`)
  fs.writeFileSync(temp, REPAIR_SCRIPT, { mode: 0o600 })
  fs.renameSync(temp, file)
  return { written: true, path: file }
}

/**
 * One-line launch hint for the current platform, consumed by the panel.
 * Windows gets the exact command; other platforms get the manual path.
 */
export function repairHint() {
  if (process.platform === 'win32') {
    return `powershell -ExecutionPolicy Bypass -File "${repairScriptPath()}"`
  }
  return repairScriptPath()
}

/** HOME hint for non-Windows platforms (informational only). */
export function homeHint() {
  return path.join(os.homedir(), '.dsh', 'electron-user-data', 'Network')
}
