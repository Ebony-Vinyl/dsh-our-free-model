const zhKeys = Object.keys(DICT.zh)
const enKeys = Object.keys(DICT.en)
if (zhKeys.length !== enKeys.length || zhKeys.some(key => DICT.en[key] === undefined)) {
  // 双语键必须一一对应；缺键的开发期提示优于运行时把键名渲染给用户。
  console.warn('i18n: dictionary keys mismatch', zhKeys.filter(key => DICT.en[key] === undefined))
}

export function getLocale() {
  return current
}

export function switchLocale(next) {
  if (next !== 'en' && next !== 'zh') return
  try { localStorage.setItem(STORAGE, next) } catch { /* 存储不可用时仅本次会话切换 */ }
  location.reload()
}

/** 数字与时间格式化随语言切换。 */
export function numLocale() {
  return current === 'en' ? 'en-US' : 'zh-CN'
}

/** 共享的 CHANNEL_PROVIDERS 是中文数据：英文界面按 id 取这里的表，中文回退原值。 */
export function providerText(channel, field) {
  if (current !== 'en') return channel[field]
  return DICT.en[`provider.${field}.${channel.id}`] ?? channel[field]
}

const t = Object.assign(key => {
  const value = key === undefined ? key : DICT[current][key]
  if (value !== undefined) return value
  return key
}, {
  get locale() { return current },
  format(key, values = {}) {
    const template = DICT[current][key] ?? key
    return template.replace(/\{(\w+)\}/g, (placeholder, name) => values[name] ?? placeholder)
  },
})
export { t }

/** 渠道桥：先查控制台字典，缺键时走调用方给的第二本字典（shared.DICT）。 */
export function bindT(fallback) {
  const bound = Object.assign(key => {
    const own = DICT[current][key]
    if (own !== undefined) return own
    return fallback ? fallback(key) : key
  }, {
    get locale() { return current },
    format(key, values = {}) {
      const own = DICT[current][key]
      const template = own !== undefined ? own : fallback ? fallback(key) : key
      return template.replace(/\{(\w+)\}/g, (placeholder, name) => values[name] ?? placeholder)
    },
  })
  return bound
}

export default DICT
