#!/usr/bin/env node
/**
 * ofm-mcp-bridge — MCP stdio bridge for the Our Free Model standalone service.
 *
 * Tools:
 *   ofm_models    — list models available on the local gateway
 *   ofm_chat      — one prompt in, one reply out
 *   ofm_usage     — local usage statistics (no upstream request)
 *   ofm_channels  — account-channel overview (accounts, credits, EAC pool)
 *   ofm_checkin   — daily check-in / claim credits for logged-in channels
 *   ofm_ledger    — token ledger snapshot + per-channel credit balances
 *
 * stdout carries JSON-RPC only. All diagnostics go to stderr.
 * Configuration is environment-only; nothing here reads or stores upstream
 * credentials, and nothing here logs prompt text or responses.
 */
import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { StdioServerTransport } from "@modelcontextprotocol/sdk/server/stdio.js";
import { z } from "zod";
import { readFileSync } from "node:fs";
import path from "node:path";
import { Supervisor, envConfig, log } from "./supervisor.mjs";
import { RetryBudget, sleepWithBackoff, isBudgetRejection } from "./retry.mjs";

const cfg = envConfig();
const supervisor = new Supervisor(cfg);

// The local gateway key is generated by the standalone service into its own
// data dir; it authenticates loopback requests only and is not an upstream
// credential. Reading it from the same data dir keeps setup zero-config while
// keeping the secret out of env vars and logs. OFM_KEY overrides.
let cachedKey = undefined;
function localKey() {
  if (cfg.key) return cfg.key;
  if (cachedKey === undefined) {
    try {
      cachedKey = JSON.parse(readFileSync(path.join(cfg.dataDir, "settings.json"), "utf8")).forwardKey || "";
    } catch {
      cachedKey = "";
    }
  }
  return cachedKey;
}

async function ofmFetch(apiPath, init = {}) {
  await supervisor.ensure();
  const key = localKey();
  const r = await fetch(`${cfg.url}${apiPath}`, {
    ...init,
    headers: {
      "Content-Type": "application/json",
      ...(key ? { Authorization: `Bearer ${key}` } : {}),
      ...(init.headers || {}),
    },
  });
  const retryAfter = r.headers.get("retry-after") || "";
  const text = await r.text();
  let body;
  try {
    body = JSON.parse(text);
  } catch {
    body = { raw: text.slice(0, 500) };
  }
  if (!r.ok) {
    const detail =
      typeof body?.error?.message === "string" ? body.error.message : JSON.stringify(body).slice(0, 300);
    const err = new Error(`OFM ${apiPath} -> HTTP ${r.status}: ${detail}`);
    err.retryAfter = retryAfter;
    err.status = r.status;
    throw err;
  }
  return body;
}

/** Extract usable text from a chat completion choice. */
function extract(body) {
  const choice = body?.choices?.[0];
  const msg = choice?.message ?? {};
  let text = "";
  if (typeof msg.content === "string") text = msg.content;
  else if (Array.isArray(msg.content)) text = msg.content.map((c) => c.text || c.content || "").join("");
  const toolCalls = Array.isArray(msg.tool_calls) && msg.tool_calls.length > 0;
  return { text, toolCalls, finish: (choice?.finish_reason || "").trim() };
}

function defaultMaxTokens() {
  const n = Number(process.env.OFM_MAX_TOKENS || "");
  return Number.isFinite(n) && n > 0 ? n : undefined; // undefined -> omit, upstream decides
}

const NO_TOOLS_NOTE =
  "[note] The upstream model emitted tool calls (it behaves like a CLI agent). " +
  "This request is a plain API call with no tools; retried once with a strict text-only instruction.";

const server = new McpServer({ name: "ofm-mcp-bridge", version: "0.2.0" });

server.tool(
  "ofm_models",
  "List models available on the local Our Free Model gateway, with context window metadata when provided.",
  {},
  async () => {
    const data = await ofmFetch("/v1/models");
    const models = (data.data || []).map((m) => ({
      id: m.id,
      context_window: m.context_window,
      owned_by: m.owned_by || m.provider || undefined,
    }));
    return { content: [{ type: "text", text: JSON.stringify({ count: models.length, models }, null, 2) }] };
  }
);

server.tool(
  "ofm_chat",
  "Send one prompt to a model on the local Our Free Model gateway and return the reply text. " +
    "Call ofm_models first to pick a model id. Do not send secrets: free upstreams may log prompts.",
  {
    prompt: z.string().describe("User prompt to send."),
    model: z.string().optional().describe("Model id from ofm_models. Defaults to the first available model."),
    system: z.string().optional().describe("Optional system prompt."),
  },
  async ({ prompt, model, system }) => {
    if (!model) {
      const data = await ofmFetch("/v1/models");
      const ids = (data.data || []).map((m) => m.id);
      if (!ids.length) throw new Error("No models available on the OFM service.");
      model = ids[0];
    }
    const budget = new RetryBudget();
    const baseMessages = [];
    if (system) baseMessages.push({ role: "system", content: system });
    baseMessages.push({ role: "user", content: prompt });

    const notes = [];
    let maxTokens = defaultMaxTokens();
    let disableRewrite = process.env.OFM_DISABLE_PROMPT_REWRITE === "1";

    async function call(messages, tokens) {
      for (;;) {
        try {
          const payload = { model, messages, stream: false };
          if (tokens !== undefined) payload.max_tokens = tokens;
          return await ofmFetch("/v1/chat/completions", { method: "POST", body: JSON.stringify(payload) });
        } catch (err) {
          if (isBudgetRejection(err.message) && budget.take()) {
            const halved = Math.floor((tokens ?? 32768) / 2);
            if (halved >= 256) {
              notes.push(`[note] max_tokens=${tokens ?? "upstream default"} rejected by upstream, halved to ${halved}.`);
              tokens = halved;
              continue;
            }
          }
          if (err.status === 429 && budget.take()) {
            log("upstream 429, backing off (honoring Retry-After if present)");
            await sleepWithBackoff(1, err.retryAfter);
            continue;
          }
          throw err;
        }
      }
    }

    let body = await call(baseMessages, maxTokens);
    let { text, toolCalls, finish } = extract(body);

    // Model acted like a CLI agent and emitted tool calls -> one strict retry.
    if (!text.trim() && toolCalls) {
      if (disableRewrite) {
        throw new Error(
          "Model emitted tool_calls instead of answering and prompt rewriting is disabled " +
            "(OFM_DISABLE_PROMPT_REWRITE=1). Raw: " + JSON.stringify(body).slice(0, 400)
        );
      }
      notes.push(NO_TOOLS_NOTE);
      log("model emitted tool_calls; retrying with strict text-only system prompt");
      const strict = [
        {
          role: "system",
          content:
            (system ? system + "\n\n" : "") +
            "You are called via a plain API with NO tools. Never emit tool_calls or JSON. " +
            "Answer the user directly in plain text.",
        },
        { role: "user", content: prompt },
      ];
      body = await call(strict, maxTokens);
      ({ text, toolCalls, finish } = extract(body));
    }

    // Reasoning consumed the whole budget with no visible content -> double once.
    if (!text.trim() && !toolCalls && (finish === "length" || !text)) {
      const doubled = Math.min((maxTokens ?? 32768) * 2, 262144);
      if (budget.take() && doubled !== maxTokens) {
        notes.push(
          `[note] Empty reply (reasoning consumed the budget, finish_reason=${finish || "n/a"}). Retried with max_tokens=${doubled}.`
        );
        log(`empty reply (finish=${finish || "n/a"}); retrying with max_tokens=${doubled}`);
        maxTokens = doubled;
        body = await call(baseMessages, maxTokens);
        ({ text, toolCalls, finish } = extract(body));
      }
    }

    if (!text.trim()) {
      throw new Error(
        `Model returned no visible text (finish_reason=${finish || "n/a"}${toolCalls ? ", emitted tool_calls" : ""}).`
      );
    }

    const noteText = notes.length ? notes.join("\n") + "\n" : "";
    return { content: [{ type: "text", text: `[model: ${body.model || model}]\n${noteText}${text}` }] };
  }
);

server.tool(
  "ofm_usage",
  "Show local usage statistics of the Our Free Model service (tokens, calls, failures; today / last 7 days / cumulative). Reads a local file, makes no upstream request.",
  {},
  async () => {
    let raw;
    try {
      raw = JSON.parse(readFileSync(path.join(cfg.dataDir, "stats.json"), "utf8"));
    } catch {
      return { content: [{ type: "text", text: "No usage stats yet (stats.json not found or unreadable)." }] };
    }
    const d = new Date();
    const fmt = (x) =>
      `${x.getFullYear()}-${String(x.getMonth() + 1).padStart(2, "0")}-${String(x.getDate()).padStart(2, "0")}`;
    const localDate = fmt(d);
    const weekAgo = fmt(new Date(d.getTime() - 6 * 86400000));

    const sumModels = (obj) => {
      const out = {};
      for (const [id, m] of Object.entries(obj || {})) {
        out[id] = {
          calls: m.calls || 0, failed: m.failed || 0,
          input: m.input || 0, output: m.output || 0,
          reasoning: m.reasoning || 0, cacheRead: m.cacheRead || 0,
        };
      }
      return out;
    };
    const totals = (obj) => {
      const t = { calls: 0, failed: 0, input: 0, output: 0, reasoning: 0, cacheRead: 0 };
      for (const m of Object.values(obj || {})) for (const k of Object.keys(t)) t[k] += m[k] || 0;
      return t;
    };

    const days = raw.days || {};
    const todayModels = sumModels(days[localDate]?.models);
    const weekModels = {};
    const weekTotals = { calls: 0, failed: 0, input: 0, output: 0, reasoning: 0, cacheRead: 0 };
    for (const [date, entry] of Object.entries(days)) {
      if (date < weekAgo) continue;
      for (const [id, m] of Object.entries(sumModels(entry.models))) {
        if (!weekModels[id]) weekModels[id] = { ...m };
        else for (const k of Object.keys(m)) weekModels[id][k] += m[k];
      }
      for (const k of Object.keys(weekTotals)) weekTotals[k] += totals(entry.models)[k];
    }

    const result = {
      today: { date: localDate, totals: totals(days[localDate]?.models), models: todayModels },
      last7days: { from: weekAgo, totals: weekTotals, models: weekModels },
      cumulative: {
        turns: raw.logical?.turns, failed: raw.logical?.failed, recovered: raw.logical?.recovered,
        models: sumModels(raw.models),
      },
      note:
        "The anonymous free lane has no quota/balance system; this is usage, not remaining credit. " +
        "Account-channel credits are shown in the web console at " + cfg.url,
    };
    return { content: [{ type: "text", text: JSON.stringify(result, null, 2) }] };
  }
);

// --- Account channels (management RPC) -------------------------------------
// These tools talk to the local service's management API on the same loopback
// address, authenticated with the same local forwardKey. They only read or
// drive the user's own logged-in channel accounts; no upstream credentials
// ever pass through the bridge.

const OFM_MANAGEMENT_PREFIX = "/api/management";
const CHANNEL_PROVIDERS = [
  "lobsterai", "qoder", "qodercn", "trae", "cline", "loomy",
  "raccoon", "minimax", "zcode", "opencode", "gemini",
];

async function channelRpc(method, payload) {
  const body = await ofmFetch(`${OFM_MANAGEMENT_PREFIX}/channels/rpc`, {
    method: "POST",
    body: JSON.stringify({ method, payload }),
  });
  if (body && body.ok === false) {
    const msg = body?.error?.message || JSON.stringify(body).slice(0, 300);
    throw new Error(`channel rpc ${method} failed: ${msg}`);
  }
  return body?.value !== undefined ? body.value : body;
}

server.tool(
  "ofm_channels",
  "Overview of account channels (trae/lobsterai/qoder/cline/loomy/raccoon/minimax/zcode/opencode/gemini) " +
    "and the EAC pool: accounts logged in per channel, model counts, credit balances. Read-only.",
  {},
  async () => {
    const status = await channelRpc("provider.status", { providers: CHANNEL_PROVIDERS });
    const statuses = status?.statuses || {};
    const out = { channels: {}, eac: undefined, note: "" };
    let loggedIn = 0;
    for (const [id, s] of Object.entries(statuses)) {
      const entry = { models: s.models, accounts: s.accounts };
      if (s.accounts?.total > 0) {
        loggedIn++;
        try {
          const credits = await channelRpc("credits.status", { provider: id });
          entry.credits = credits?.accounts ?? credits;
        } catch (e) {
          entry.credits = `unavailable: ${String(e.message || e).slice(0, 120)}`;
        }
      }
      out.channels[id] = entry;
    }
    try {
      out.eac = await ofmFetch(`${OFM_MANAGEMENT_PREFIX}/eac/pool`);
    } catch {}
    out.note =
      loggedIn === 0
        ? "No account channels are logged in yet. To add one, open the web console " +
          `${cfg.url} -> 聚合渠道 -> connect an account (login flows need browser interaction). ` +
          "The anonymous free lane works without any account."
        : `${loggedIn} channel(s) have logged-in accounts.`;
    return { content: [{ type: "text", text: JSON.stringify(out, null, 2) }] };
  }
);

server.tool(
  "ofm_checkin",
  "Run daily check-in (claim credits) for all logged-in account channels, or a single one via `provider`. " +
    "No-op for channels without logged-in accounts.",
  {
    provider: z
      .string()
      .optional()
      .describe("Limit to one channel id (e.g. trae, lobsterai, qoder). Defaults to all logged-in channels."),
  },
  async ({ provider }) => {
    const targets = provider ? [provider] : CHANNEL_PROVIDERS;
    const status = await channelRpc("provider.status", { providers: targets });
    const statuses = status?.statuses || {};
    const results = {};
    for (const id of targets) {
      const s = statuses[id];
      if (!s) { results[id] = "unsupported channel id"; continue; }
      if (!s.accounts?.total) { results[id] = "skipped: no logged-in account"; continue; }
      try {
        results[id] = (await channelRpc("credits.claimAll", { provider: id })) ?? "done";
      } catch (e) {
        results[id] = `failed: ${String(e.message || e).slice(0, 160)}`;
      }
    }
    return { content: [{ type: "text", text: JSON.stringify({ checkin: results }, null, 2) }] };
  }
);

server.tool(
  "ofm_ledger",
  "Token ledger snapshot of the gateway plus credit balances for a channel (needs a logged-in account " +
    "for balances; the ledger itself is always available).",
  {
    provider: z.string().optional().describe("Channel id for credit balances (e.g. lobsterai, trae)."),
    limit: z.number().optional().describe("Max ledger entries (default 20)."),
  },
  async ({ provider, limit }) => {
    const out = {};
    try {
      const ledger = await channelRpc("usage.tokenLedger", { limit: limit ?? 20 });
      out.ledger = ledger?.snapshot ?? ledger;
    } catch (e) {
      out.ledger = `unavailable: ${String(e.message || e).slice(0, 120)}`;
    }
    if (provider) {
      try {
        out.balances = await channelRpc("credits.balances", { provider });
      } catch (e) {
        out.balances = `unavailable: ${String(e.message || e).slice(0, 120)}`;
      }
    }
    return { content: [{ type: "text", text: JSON.stringify(out, null, 2) }] };
  }
);

const transport = new StdioServerTransport();
await server.connect(transport);
transport.onclose = () => {
  supervisor.onClientExit().catch(() => {});
};
